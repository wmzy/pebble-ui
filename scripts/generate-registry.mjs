#!/usr/bin/env node
/**
 * Generate an agent-installable registry (dist/registry.json) for the
 * agent components exported under the `// agent components` section of
 * src/lib/index.ts (ChatMessage … AsyncSection). Items install through
 * the shadcn CLI — as a distribution channel, not a source-vending
 * format (see the wrapper design below).
 *
 * ── Design (experimental) ─────────────────────────────────────────────
 * A shadcn registry normally vendors component *source* into the
 * consumer's project. That is not viable for haze-ui: the components are
 * compiled CSS-in-JS (linaria) whose classes only exist after a library
 * build, and every rule is written against `--haze-*` design tokens.
 * Copying the source would produce files that neither style nor build.
 *
 * So each registry item ships a thin *wrapper* file instead: it imports
 * the named component(s) from the npm package plus their stylesheet
 * (`haze-ui/css/<family>.css`, family resolved from the build's own
 * dist/css-manifest.json — never hand-maintained), and re-exports them.
 * `npx shadcn add chat-message` therefore yields a customization layer
 * the consumer owns, while `haze-ui` remains a normal npm dependency
 * that keeps updating underneath. Consumers apply the theme exactly as
 * the docs app and examples/ do: the `lightTheme` (+ `spacing` +
 * `typography`) classes on a root element — see the wrapper header.
 *
 * Each item: { name, type: 'registry:component', title, description,
 * dependencies: ['haze-ui'], files: [{ path: 'components/haze/<name>.tsx',
 * content: wrapper source, type: 'registry:component' }] }.
 *
 * Run AFTER `pnpm build` (the script reads dist/css-manifest.json and
 * fails fast when it is missing). Suggested wiring: append
 * `node scripts/generate-registry.mjs` to the build chain.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const rootDir = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const distDir = path.join(rootDir, 'dist');
const manifestPath = path.join(distDir, 'css-manifest.json');
const barrelPath = path.join(rootDir, 'src/lib/index.ts');

function fail(message) {
  console.error(`generate-registry: ${message}`);
  process.exit(1);
}

const kebab = (name) =>
  name.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/([A-Z]+)([A-Z][a-z])/g, '$1-$2').toLowerCase();

// ---- inputs: css-manifest (build artifact) + barrel agent section ----

let manifest;
try {
  manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
} catch (error) {
  fail(
    `cannot read ${path.relative(rootDir, manifestPath)} (${error.code ?? error.message}). ` +
      'It is produced by pnpm build via scripts/split-css.mjs — run the build first.'
  );
}

const lines = readFileSync(barrelPath, 'utf8').split('\n');
const start = lines.findIndex((l) => /^\/\/\s*agent components\s*$/.test(l));
if (start === -1) fail('no "// agent components" section found in src/lib/index.ts');
const end = lines.findIndex((l, i) => i > start && /^\/\//.test(l));
const section = lines.slice(start + 1, end === -1 ? undefined : end).join('\n');

// module path -> { components: [value exports], types: [type exports] },
// in barrel order.
const families = new Map();
for (const m of section.matchAll(
  /^export\s+(type\s+)?\{([^}]*)\}\s+from\s+['"]([^'"]+)['"]/gm
)) {
  const [, isType, names, spec] = m;
  if (!spec.startsWith('./components/')) continue;
  if (!families.has(spec)) families.set(spec, { components: [], types: [] });
  const bucket = isType ? 'types' : 'components';
  for (const clause of names.split(',')) {
    const name = clause.trim();
    if (name) families.get(spec)[bucket].push(name);
  }
}
if (families.size === 0) fail('agent components section parsed empty — barrel shape changed?');

// ---- wrapper generation ------------------------------------------------

const wrapper = ({ components, types, css }) => {
  const importList = components.join(', ');
  const typeExport =
    types.length > 0 ? `export type { ${types.join(', ')} } from 'haze-ui';\n` : '';
  return `// haze-ui agent component wrapper — generated by scripts/generate-registry.mjs.
//
// This is a thin wrapper around the published haze-ui npm package, not
// vendored component source: it re-exports the component(s) from
// 'haze-ui' and imports their stylesheet, so the package keeps updating
// underneath. Edit this file to customize — wrap, restyle, compose; that
// is what it is for. (haze-ui is compiled CSS-in-JS (linaria) styled
// against --haze-* design tokens, so vendoring the source would neither
// build nor style — forking this wrapper is the intended customization
// path.)
//
// Theming (once per app): apply the token classes to a root element, e.g.
//   import { lightTheme, spacing, typography } from 'haze-ui';
//   <div className={\`\${lightTheme} \${spacing} \${typography}\`}>…</div>
// (darkTheme is a drop-in swap). haze-ui dist modules ship their own
// 'use client' directive, so imports resolve cleanly from RSC; the
// wrapper inherits client semantics either way.

import { ${importList} } from 'haze-ui';

import 'haze-ui/css/tokens.css';
import 'haze-ui/css/${css}.css';

export { ${importList} };
${typeExport}`;
};

// One-line descriptions of the wrapped components (human-written).
const descriptions = {
  'chat-message':
    'Chat bubble with role-based layout (user / assistant / system), avatar, name, timestamp and delivery status.',
  'chat-container': 'Chat transcript scroll container with stick-to-bottom auto-scroll.',
  'chat-input': 'Message composer with a controllable value and onSend callback.',
  'streaming-text':
    'Typewriter effect that reveals streaming text character by character, with an optional cursor.',
  'markdown-renderer': 'Renders markdown content (including code blocks) for assistant responses.',
  'tool-call-card':
    'Card presenting an agent tool call — name, input, output and running state.',
  'thinking-indicator': 'Animated bouncing-dots indicator that the agent is processing.',
  'step-timeline': 'Vertical timeline of agent execution steps with per-step status.',
  'approval-card': 'Approval gate with approve / deny actions for agent-initiated operations.',
  'token-counter': 'Context-window token usage counter with budget progress.',
  'model-picker': 'Controllable dropdown for selecting the active model.',
  'conversation-list': 'Selectable list of conversations for a chat-history sidebar.',
  'diff-viewer': 'Renders the line diff between old and new content for agent-proposed edits.',
  'log-viewer': 'Scrollable log stream with severity-level filtering.',
  'async-section': 'Declarative loading / error / content states for async data.',
};

const items = [];
for (const [spec, family] of families) {
  if (family.components.length === 0) fail(`${spec} exports no component values — registry item would be empty`);

  const name = kebab(spec.split('/').pop());
  const cssFamilies = [...new Set(family.components.map((c) => manifest.families[c]))];
  if (cssFamilies.length > 1) {
    fail(`${spec} spans multiple css families (${cssFamilies.join(', ')}) — split the barrel export or inline the css`);
  }
  const css = cssFamilies[0];
  if (css === undefined) {
    const untracked = family.components.filter((c) => !manifest.noCss.includes(c));
    if (untracked.length > 0) {
      fail(`${spec} exports not present in css-manifest.json: ${untracked.join(', ')}`);
    }
    fail(`${spec} ships no css of its own (noCss in the manifest) — decide how to wrap it before adding it to the registry`);
  }
  if (css !== name) {
    fail(`css family "${css}" does not match component directory "${name}" — keep them 1:1 or teach the script the mapping`);
  }
  const description = descriptions[name];
  if (!description) fail(`no description written for "${name}" — add one to the descriptions table`);

  items.push({
    name,
    type: 'registry:component',
    title: family.components.join(' / '),
    description,
    dependencies: ['haze-ui'],
    files: [
      {
        path: `components/haze/${name}.tsx`,
        content: wrapper({ components: family.components, types: family.types, css }),
        type: 'registry:component',
      },
    ],
  });
}

const registry = {
  $schema: 'https://ui.shadcn.com/schema.json',
  name: 'haze-ui',
  homepage: 'https://github.com/wmzy/haze-ui',
  items,
};

writeFileSync(path.join(distDir, 'registry.json'), `${JSON.stringify(registry, null, 2)}\n`);

console.log(
  `generate-registry: dist/registry.json written (${items.length} items / ` +
    `${items.reduce((n, i) => n + i.title.split(' / ').length, 0)} components, ` +
    `css families resolved from css-manifest.json)`
);
